/** Renders the lucide icon named in content (e.g. `icon: piggy-bank`). Decorative by default. */
export function ContentIcon({ name, ...props }: { name: string | undefined } & LucideProps) {
  const Icon = (name && ICONS[name]) || Coins;
  return <Icon aria-hidden {...props} />;
}
