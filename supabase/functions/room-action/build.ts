// `pnpm functions:build` — bundles the room server (handler + engine + content + zod) into one
// self-contained ESM file for the Deno Edge runtime: supabase/functions/room-action/_bundle/handler.js
// Run `pnpm content:build` first (the content bundle is baked in).
import { build } from "esbuild";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contentJson = resolve(here, "../../../packages/content/dist/content.json");
if (!existsSync(contentJson)) {
  console.error("✖ packages/content/dist/content.json is missing — run `pnpm content:build` first");
  process.exit(1);
}

const result = await build({
  entryPoints: [resolve(here, "bundle-entry.ts")],
  outfile: resolve(here, "_bundle/handler.js"),
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  mainFields: ["module", "main"],
  sourcemap: true,
  legalComments: "none",
  minify: true,
  metafile: true,
  banner: { js: "// GENERATED by supabase/functions/room-action/build.ts — do not edit.\n// @ts-nocheck" },
});

// Types for the Deno entry (index.ts). Kept minimal on purpose.
writeFileSync(
  resolve(here, "_bundle/handler.d.ts"),
  `// GENERATED by build.ts
export interface PostgresJs {
  begin<T>(fn: (tx: { unsafe(text: string, params?: unknown[]): Promise<unknown[]> }) => Promise<T>): Promise<T>;
}
export type RoomResponse = { status: number; body: unknown };
export function createRoomActionHandler(sql: PostgresJs): (userId: string | null, body: unknown) => Promise<RoomResponse>;
export function handleRoomCall(deps: unknown, userId: string | null, body: unknown): Promise<RoomResponse>;
`,
);

const bytes = Object.values(result.metafile.outputs).reduce((s, o) => s + o.bytes, 0);
console.log(`✔ room-action bundle written (${Math.round(bytes / 1024)} KB incl. source map)`);
